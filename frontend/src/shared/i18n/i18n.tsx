export type MessageKey = keyof (typeof messages)['fr'];

/**
 * Reads a key in a specific locale, independent of the current UI locale
 * (e.g. bilingual print material). Components should normally use `useI18n().t`.
 */
export function translate(locale: Locale, key: MessageKey): string {
  return messages[locale][key];
}

/** Keys defined for a locale (used to check that both catalogues match). */
export function messageKeys(locale: Locale): string[] {
  return Object.keys(messages[locale]);
}

type I18nValue = {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: MessageKey) => string;
  formatTnd: (value: number) => string;
  formatDate: (value: string | Date) => string;
  formatDateTime: (value: string | Date) => string;
};

const I18nContext = createContext<I18nValue | null>(null);

function getInitialLocale(): Locale {
  const stored = window.localStorage.getItem('fideliy-locale');
  return stored === 'ar' || stored === 'fr' ? stored : 'fr';
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocale] = useState<Locale>(getInitialLocale);

  useEffect(() => {
    document.documentElement.lang = locale;
    document.documentElement.dir = locale === 'ar' ? 'rtl' : 'ltr';
    window.localStorage.setItem('fideliy-locale', locale);
  }, [locale]);

  const value = useMemo<I18nValue>(() => ({
    locale,
    setLocale,
    t: (key) => messages[locale][key],
    formatTnd: (amount) => new Intl.NumberFormat(locale === 'ar' ? 'ar-TN' : 'fr-TN', {
      style: 'currency', currency: 'TND', minimumFractionDigits: 3,
    }).format(amount),
    formatDate: (date) => new Intl.DateTimeFormat(locale === 'ar' ? 'ar-TN' : 'fr-TN', {
      dateStyle: 'medium',
    }).format(new Date(date)),
    formatDateTime: (date) => new Intl.DateTimeFormat(locale === 'ar' ? 'ar-TN' : 'fr-TN', {
      dateStyle: 'medium', timeStyle: 'short',
    }).format(new Date(date)),
  }), [locale]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const value = useContext(I18nContext);
  if (!value) throw new Error('useI18n must be used inside I18nProvider.');
  return value;
}
